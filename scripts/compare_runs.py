#!/usr/bin/env python3
"""Compare runs per contract: tests, line/branch coverage, tgnonlin time, timed-out queries.

Reads results/<run>/summary.csv (generated by collect_results.py) and writes:
  - results/comparison.csv   (one row per contract, one column group per run)
  - results/comparison.html  (same data as table; rows with differences in tests or coverage are highlighted,
                              including QUERY_UNKNOWN lines from each run's log.txt as supporting details)

Usage example:
    python3 scripts/compare_runs.py baseline qt10 qt5
"""

import csv
import gzip
import html
import os
import re
import sys

# Base directory containing results for all runs
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")

# Metrics to extract and display per run
METRICS = [
    ("tests", "tests"),          # number of generated tests
    ("line_cov", "line %"),      # line coverage percentage
    ("branch_cov", "branch %"),  # branch coverage percentage
    ("tg_time_s", "tg s"),       # tgnonlin run time in seconds
    ("timeouts", "timeouts"),    # queries that hit the per-query timeout
    ("queries", "queries"),      # SMT queries logged in query_log.txt
]


def load(run):
    """Load summary.csv data for a given run. Returns dict mapping contract -> metrics dict."""
    filepath = os.path.join(ROOT, run, "summary.csv")
    with open(filepath) as f:
        return {row["contract"]: row for row in csv.DictReader(f)}


def unknown_lines(run, contract):
    """Extract QUERY_UNKNOWN lines from the contract's log.txt or log.txt.gz for the given run.
    Returns a list of matching lines as strings."""
    log_path = os.path.join(ROOT, run, "report", contract, "log.txt")
    content = ""
    # Try reading either plain text log or gzipped log
    for path, opener in ((log_path, open), (log_path + ".gz", gzip.open)):
        try:
            with opener(path, "rt", encoding="utf-8", errors="replace") as f:
                content = f.read()
            break
        except OSError:
            continue
    # Extract lines matching QUERY_UNKNOWN pattern
    pattern = r"QUERY_UNKNOWN query=\d+ reason=\S+ timeout_ms=\d+ cur_bnd=\d+ depth=\d+"
    return re.findall(pattern, content)


def main():
    # Determine runs to compare from command-line arguments or default list
    runs = sys.argv[1:] or ["baseline", "qt10", "qt5"]

    # Load all runs' summary data
    data = {run: load(run) for run in runs}

    # Get all unique contracts present across runs
    contracts = sorted(set().union(*[d.keys() for d in data.values()]))

    # CSV header: contract + one column per run and metric (column names, not display labels) + 'changed'
    header = ["contract"] + [f"{run}:{metric}" for run in runs for metric, _ in METRICS] + ["changed"]
    rows = []

    for contract in contracts:
        # Extract metric values for the contract from each run (or empty dict if missing)
        run_vals = {run: data[run].get(contract, {}) for run in runs}

        # Define key based on tests, line coverage, and branch coverage to detect changes
        def key(run_key):
            return (
                run_vals[run_key].get("tests", ""),
                run_vals[run_key].get("line_cov", ""),
                run_vals[run_key].get("branch_cov", "")
            )

        # If any run differs on the key metrics, mark contract as changed
        changed = len({key(run) for run in runs}) > 1

        # Build one row of collected metric values per run plus change flag
        row = [contract] + [run_vals[run].get(m, "") for run in runs for m, _ in METRICS] + [changed]
        rows.append(row)

    # Write out comparison.csv with full data
    csv_path = os.path.join(ROOT, "comparison.csv")
    with open(csv_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows(rows)

    # Helper to sum numeric metric values across all contracts for a run
    def total(run, metric):
        values = [data[run][c][metric] for c in data[run] if data[run][c].get(metric) not in ("", None)]
        return sum(float(v) for v in values)

    # A run whose tgnonlin writes no query log (e.g. the unmodified baseline binary) has no query data
    def logs_queries(run):
        return any(data[run][c].get("queries") not in ("", None) for c in data[run])

    # Create HTML table header grouping columns by run and metric labels
    head_html = "".join(f"<th colspan='{len(METRICS)}'>{html.escape(run)}</th>" for run in runs)
    subheader_html = "".join(f"<th>{label}</th>" for _ in runs for _, label in METRICS)

    body_html = []
    # For each contract row, create an HTML row; highlight if changed
    for row in rows:
        contract_name, changed_flag = row[0], row[-1]
        # Escape and format data cells (all except contract and changed flag)
        cells_html = "".join(f"<td>{html.escape(str(val))}</td>" for val in row[1:-1])

        # Main data row, CSS class highlights changed contracts
        row_class = "chg" if changed_flag else ""
        body_html.append(f"<tr class='{row_class}'><td>{html.escape(contract_name)}</td>{cells_html}</tr>")

        # If changed, also add a detail row showing QUERY_UNKNOWN entries for each run
        if changed_flag:
            evidences = []
            for run in runs:
                qlines = unknown_lines(run, contract_name)
                if qlines:
                    evidence_text = "<br>".join(map(html.escape, qlines))
                elif logs_queries(run):
                    evidence_text = "no unknown queries"
                else:
                    evidence_text = "not logged by this tgnonlin"
                evidences.append(f"<b>{html.escape(run)}</b>: {evidence_text}")

            colspan = 1 + len(runs) * len(METRICS)
            body_html.append(f"<tr class='ev'><td colspan='{colspan}'>{'<br>'.join(evidences)}</td></tr>")

    # Summarize overall stats per run to include in HTML
    def timed_out(run):
        return f"{total(run, 'timeouts'):.0f} queries timed out" if logs_queries(run) else "queries not logged"

    summary_html = "".join(
        f"<li><b>{html.escape(run)}</b>: {sum(1 for c in data[run] if data[run][c].get('status') == 'ok')} contracts with tests, "
        f"{int(total(run, 'tests'))} tests, {timed_out(run)}, tgnonlin {total(run, 'tg_time_s'):.0f} s total</li>"
        for run in runs
    )

    # Complete HTML page with embedded CSS styling and explanatory text
    html_page = f"""<!doctype html>
<meta charset="utf-8">
<title>SolTG query-timeout comparison</title>
<style>
  body {{ font:14px system-ui; margin:24px }}
  table {{ border-collapse:collapse }}
  td, th {{ border:1px solid #ccc; padding:3px 6px; text-align:right }}
  td:first-child {{ text-align:left; font-family:monospace }}
  tr.chg td {{ background:#fff3d6 }}
  tr.ev td {{ text-align:left; font:12px monospace; background:#fafafa }}
</style>
<h1>Per-query Z3 timeout: {' vs '.join(html.escape(r) for r in runs)}</h1>
<ul>{summary_html}</ul>
<p>Highlighted rows: tests, line or branch coverage differ between runs; the row below each lists the QUERY_UNKNOWN lines from that contract's log.txt in every run.</p>
<table>
  <tr><th rowspan=2>contract</th>{head_html}</tr>
  <tr>{subheader_html}</tr>
  {''.join(body_html)}
</table>
"""

    # Write HTML report
    html_path = os.path.join(ROOT, "comparison.html")
    with open(html_path, "w") as f:
        f.write(html_page)

    # Report summary on stdout
    changed_count = sum(1 for r in rows if r[-1])
    print(f"{len(rows)} contracts, {changed_count} changed -> results/comparison.csv, results/comparison.html")


if __name__ == "__main__":
    main()
